//! Geometry of a modular coil set and its distance to the plasma.

use crate::coils::{arc_step, coil_points, SampledCoils};
use crate::equilibrium::{cartesian, interpolate, surface_point, Coefficients, Equilibrium};
use crate::error::{ensure, Code, Error};
use crate::limits::{FIT_SURFACES, MAX_COILS, MAX_SURFACE};
use crate::num::{dot, norm, real, scale, sub, Vec3};
use core::f64::consts::TAU;

const BAD: Code = Code::Numeric;
/// Relative tolerance when comparing coils for symmetry.
const SYMMETRY_TOLERANCE: f64 = 1.0e-4;

/// Overall dimensions of the coil set.
#[derive(Debug, Clone, Copy)]
pub struct CoilMeasures {
    /// Arc-length-weighted mean cylindrical radius of all filament points [m].
    pub r_major: f64,
    /// Arc-length-weighted mean distance of the points from the circle
    /// `R = r_major`, `z = mean z` [m].
    pub r_minor: f64,
    /// Sum of the lengths of all coil centre filaments [m].
    pub total_length: f64,
    /// Full vertical extent of the coil set [m].
    pub height: f64,
    /// Smallest radius of curvature of any filament [m].
    pub min_bend_radius: f64,
    /// Mean area of the surfaces of revolution generated by the coils [m^2].
    pub surface_area: f64,
}

/// Coils grouped into sets that are images of one another; a reusable buffer.
#[derive(Debug, Clone)]
pub struct SymmetryClasses {
    /// Number of classes found.
    pub n_classes: usize,
    /// Index of one coil per class.
    pub representatives: Vec<usize>,
    /// Number of coils in each class.
    pub multiplicity: Vec<usize>,
    /// Class index of each coil.
    pub class_of: Vec<usize>,
}

/// A buffer for the symmetry classes of `n_coils` coils.
///
/// # Errors
/// Returns an error if the number of coils is outside the limits.
pub fn new_symmetry_classes(n_coils: usize) -> Result<SymmetryClasses, Error> {
    ensure(n_coils >= 1, BAD, "at least one coil is needed")?;
    ensure(n_coils <= MAX_COILS, Code::Limit, "too many coils")?;
    Ok(SymmetryClasses {
        n_classes: 0,
        representatives: vec![0; n_coils],
        multiplicity: vec![0; n_coils],
        class_of: vec![0; n_coils],
    })
}

/// Arc-length-weighted mean cylindrical radius and height of all points.
fn mean_position(coils: &SampledCoils) -> Result<(f64, f64), Error> {
    let (mut total, mut radius_sum, mut height_sum) = (0.0, 0.0, 0.0);
    for coil in 0..coils.n_coils {
        let weight = arc_step(coils, coil)?;
        for point in coil_points(coils, coil)? {
            total += weight;
            radius_sum += weight * point[0].hypot(point[1]);
            height_sum += weight * point[2];
        }
    }
    ensure(total > 0.0, BAD, "the coil set has no length")?;
    ensure(radius_sum > 0.0, BAD, "the coil set lies on the vertical axis")?;
    Ok((radius_sum / total, height_sum / total))
}

/// Overall dimensions of the coil set.
///
/// The radii are exact for circular coils centred on the circle
/// `R = r_major`. The surface area equals `2 pi * r_major * mean coil
/// length`: every coil length element is given a toroidal width `2 pi R / N`.
///
/// # Errors
/// Returns an error if the coil set has no extent or a value is not finite.
pub fn coil_measures(coils: &SampledCoils) -> Result<CoilMeasures, Error> {
    let (r_major, z_mean) = mean_position(coils)?;
    let (mut minor_sum, mut total, mut swept) = (0.0, 0.0, 0.0);
    let (mut lowest, mut highest, mut sharpest) = (f64::INFINITY, f64::NEG_INFINITY, 0.0_f64);
    for coil in 0..coils.n_coils {
        let weight = arc_step(coils, coil)?;
        for point in coil_points(coils, coil)? {
            let radius = point[0].hypot(point[1]);
            minor_sum += weight * (radius - r_major).hypot(point[2] - z_mean);
            swept += weight * radius;
            lowest = lowest.min(point[2]);
            highest = highest.max(point[2]);
        }
        total += coils.lengths[coil];
    }
    for value in &coils.curvature {
        sharpest = sharpest.max(*value);
    }
    ensure(sharpest > 0.0 && sharpest.is_finite(), BAD, "the coils have no curvature")?;
    ensure(highest > lowest && total > 0.0, BAD, "the coil set has no extent")?;
    Ok(CoilMeasures {
        r_major,
        r_minor: minor_sum / total,
        total_length: total,
        height: highest - lowest,
        min_bend_radius: 1.0 / sharpest,
        surface_area: TAU * swept / real(coils.n_coils)?,
    })
}

/// Squared distance from a point to the nearest segment of a closed polygon.
fn polygon_distance_squared(point: Vec3, vertices: &[Vec3]) -> f64 {
    let mut nearest = f64::INFINITY;
    let mut start = vertices[vertices.len() - 1];
    for vertex in vertices {
        let segment = sub(*vertex, start);
        let offset = sub(point, start);
        let along = (dot(offset, segment) / dot(segment, segment)).clamp(0.0, 1.0);
        let gap = sub(offset, scale(segment, along));
        nearest = nearest.min(dot(gap, gap));
        start = *vertex;
    }
    nearest
}

/// Shortest distance from coil `coil` to every coil. The entry for the coil
/// itself is infinite.
///
/// # Errors
/// Returns an error if `coil` is not a valid index or `out` does not hold
/// one value per coil.
pub fn coil_distances(coils: &SampledCoils, coil: usize, out: &mut [f64]) -> Result<(), Error> {
    ensure(coil < coils.n_coils, BAD, "a coil index is out of range")?;
    ensure(out.len() == coils.n_coils, BAD, "one distance per coil is needed")?;
    let own = coil_points(coils, coil)?;
    for (other, distance) in out.iter_mut().enumerate() {
        let mut nearest = f64::INFINITY;
        if other != coil {
            let vertices = coil_points(coils, other)?;
            for point in own {
                nearest = nearest.min(polygon_distance_squared(*point, vertices));
            }
        }
        *distance = nearest.sqrt();
    }
    Ok(())
}

/// Whether two angles differ by a multiple of `period`, within tolerance.
fn same_angle(first: f64, second: f64, period: f64) -> bool {
    let difference = (first - second + 0.5 * period).rem_euclid(period) - 0.5 * period;
    difference.abs() < SYMMETRY_TOLERANCE
}

/// Whether `other` is an image of `coil` under the device symmetry.
fn is_image(
    coils: &SampledCoils,
    coil: usize,
    other: usize,
    nfp: usize,
    stellsym: bool,
) -> Result<bool, Error> {
    ensure(coil < coils.n_coils && other < coils.n_coils, BAD, "a coil index is out of range")?;
    let period = TAU / real(nfp)?;
    let (mut size, mut strongest) = (0.0_f64, 0.0_f64);
    for (centroid, current) in coils.centroids.iter().zip(coils.currents.iter()) {
        size = size.max(centroid[0].hypot(centroid[1]));
        strongest = strongest.max(current.abs());
    }
    ensure(size > 0.0 && strongest > 0.0, BAD, "the coil set has no extent or no current")?;
    let (a, b) = (coils.centroids[coil], coils.centroids[other]);
    let (phi_a, phi_b) = (a[1].atan2(a[0]), b[1].atan2(b[0]));
    let length = coils.lengths[coil];
    let alike = (b[0].hypot(b[1]) - a[0].hypot(a[1])).abs() < SYMMETRY_TOLERANCE * size
        && (coils.lengths[other] - length).abs() < SYMMETRY_TOLERANCE * length
        && (coils.currents[other].abs() - coils.currents[coil].abs()).abs()
            < SYMMETRY_TOLERANCE * strongest;
    let rotated =
        same_angle(phi_b, phi_a, period) && (b[2] - a[2]).abs() < SYMMETRY_TOLERANCE * size;
    let flipped = stellsym
        && same_angle(phi_b, -phi_a, period)
        && (b[2] + a[2]).abs() < SYMMETRY_TOLERANCE * size;
    Ok(alike && (rotated || flipped))
}

/// Group coils that map onto each other under the device symmetry.
///
/// Two coils are equivalent if one is the other rotated by a multiple of
/// `2 pi / nfp`, optionally combined with the stellarator-symmetry flip
/// `(R, phi, z) -> (R, -phi, -z)`. Equivalence is tested on the centroid,
/// the length and the absolute current. If the coil set does not have the
/// symmetry, every coil forms its own class and results stay correct.
///
/// # Errors
/// Returns an error if `nfp` is zero or `out` was created for a different
/// number of coils.
pub fn symmetry_classes(
    coils: &SampledCoils,
    nfp: usize,
    stellsym: bool,
    out: &mut SymmetryClasses,
) -> Result<(), Error> {
    ensure(nfp >= 1, BAD, "nfp must be at least 1")?;
    ensure(out.class_of.len() == coils.n_coils, BAD, "the class buffer does not match the coils")?;
    let unassigned = coils.n_coils;
    out.class_of.fill(unassigned);
    out.n_classes = 0;
    for coil in 0..coils.n_coils {
        if out.class_of[coil] == unassigned {
            let class = out.n_classes;
            out.representatives[class] = coil;
            out.multiplicity[class] = 0;
            for other in coil..coils.n_coils {
                if out.class_of[other] == unassigned && is_image(coils, coil, other, nfp, stellsym)?
                {
                    out.class_of[other] = class;
                    out.multiplicity[class] += 1;
                }
            }
            out.n_classes += 1;
        }
    }
    ensure(out.n_classes >= 1, BAD, "no symmetry class was found")?;
    Ok(())
}

/// Largest centre-to-centre distance between neighbouring coils [m].
///
/// Measured between the centroids of coils that are adjacent in toroidal
/// order. For evenly spaced coils this is the coil spacing at the mean coil
/// radius. The widths of the coils themselves are not subtracted; PROCESS
/// applies factors of 0.4 and 0.8 to obtain port sizes. `order` is scratch
/// space with one entry per coil.
///
/// # Errors
/// Returns an error if `order` does not hold one entry per coil.
pub fn port_width(coils: &SampledCoils, order: &mut [usize]) -> Result<f64, Error> {
    let count = coils.n_coils;
    ensure(order.len() == count, BAD, "one order entry per coil is needed")?;
    ensure(count <= MAX_COILS, Code::Limit, "too many coils")?;
    for (index, entry) in order.iter_mut().enumerate() {
        *entry = index;
    }
    // Stable insertion sort by the toroidal angle of the centroid.
    for sorted in 1..count {
        for position in (1..=sorted).rev() {
            let (left, right) =
                (coils.centroids[order[position - 1]], coils.centroids[order[position]]);
            if left[1].atan2(left[0]) > right[1].atan2(right[0]) {
                order.swap(position - 1, position);
            }
        }
    }
    let mut widest = 0.0_f64;
    for index in 0..count {
        let next = coils.centroids[order[(index + 1) % count]];
        widest = widest.max(norm(sub(next, coils.centroids[order[index]])));
    }
    Ok(widest)
}

/// Mark the coils that can be closest to the first field period.
///
/// # Errors
/// Returns an error if `near` does not hold one flag per coil.
pub fn select_near_period(
    coils: &SampledCoils,
    nfp: usize,
    near: &mut [bool],
) -> Result<(), Error> {
    ensure(near.len() == coils.n_coils, BAD, "one flag per coil is needed")?;
    ensure(nfp >= 1, BAD, "nfp must be at least 1")?;
    let period = TAU / real(nfp)?;
    let mut any = false;
    for (flag, centroid) in near.iter_mut().zip(coils.centroids.iter()) {
        let phi = (centroid[1].atan2(centroid[0]) + 0.5 * period).rem_euclid(TAU);
        // The period itself plus half a period on each side.
        *flag = nfp == 1 || phi < 2.0 * period;
        any = any || *flag;
    }
    if !any {
        for flag in near.iter_mut() {
            *flag = true;
        }
    }
    Ok(())
}

/// Minimum distance between the flux surface at `s` and any coil filament [m].
///
/// The surface is sampled on `resolution` x `resolution` angles over one
/// field period; only the coils flagged in `near` are tested.
///
/// # Errors
/// Returns an error if `s` is outside `(0, 1]`, the resolution is outside
/// `8..=512`, or no coil is flagged.
pub fn plasma_coil_distance(
    eq: &Equilibrium,
    coils: &SampledCoils,
    s: f64,
    resolution: usize,
    surface: &mut Coefficients,
    near: &[bool],
) -> Result<f64, Error> {
    ensure(s > 0.0 && s <= 1.0, BAD, "s must lie in (0, 1]")?;
    ensure(
        (8..=MAX_SURFACE).contains(&resolution),
        Code::Settings,
        "the surface resolution must be 8 to 512",
    )?;
    ensure(near.len() == coils.n_coils, BAD, "one flag per coil is needed")?;
    interpolate(eq, s, surface)?;
    let mut nearest = f64::INFINITY;
    for toroidal in 0..resolution {
        let phi = TAU / real(eq.nfp)? * real(toroidal)? / real(resolution)?;
        for poloidal in 0..resolution {
            let theta = TAU * real(poloidal)? / real(resolution)?;
            let point = cartesian(&surface_point(eq, surface, theta, phi)?, phi);
            for (coil, flagged) in near.iter().enumerate() {
                if *flagged {
                    nearest =
                        nearest.min(polygon_distance_squared(point, coil_points(coils, coil)?));
                }
            }
        }
    }
    ensure(nearest.is_finite(), BAD, "no coil was selected for the plasma-coil distance")?;
    Ok(nearest.sqrt())
}

/// Slope of a least-squares straight line through the given points.
///
/// Used for the change of the minimum plasma-coil distance with the plasma
/// minor radius; the slope is -1 when all surfaces are concentric circles.
///
/// # Errors
/// Returns an error if the abscissae are all equal or a value is not finite.
pub fn fitted_slope(x: &[f64; FIT_SURFACES], y: &[f64; FIT_SURFACES]) -> Result<f64, Error> {
    let count = real(FIT_SURFACES)?;
    let (mut x_mean, mut y_mean) = (0.0, 0.0);
    for (a, b) in x.iter().zip(y.iter()) {
        x_mean += a / count;
        y_mean += b / count;
    }
    let (mut covariance, mut variance) = (0.0, 0.0);
    for (a, b) in x.iter().zip(y.iter()) {
        covariance += (a - x_mean) * (b - y_mean);
        variance += (a - x_mean) * (a - x_mean);
    }
    ensure(variance > 0.0, BAD, "the fit needs at least two distinct surfaces")?;
    ensure((covariance / variance).is_finite(), BAD, "the fitted slope is not finite")?;
    Ok(covariance / variance)
}
